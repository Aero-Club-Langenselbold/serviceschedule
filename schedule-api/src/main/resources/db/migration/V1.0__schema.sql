CREATE SEQUENCE hibernate_sequence
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
    NO CYCLE;

CREATE SEQUENCE revinfo_seq
    START WITH 1
	INCREMENT BY 50
	MINVALUE 1
	NO MAXVALUE
	CACHE 1
	NO CYCLE;

CREATE TABLE revinfo (
	rev int4 generated by default as identity,
	revtstmp int8 NULL,
	CONSTRAINT revinfo_pkey PRIMARY KEY (rev)
);

CREATE TABLE participant (
    id character varying(36) NOT NULL,
    version int4 DEFAULT 0 NOT NULL,
    firstname character varying(50) NOT NULL,
    lastname character varying(50) NOT NULL,
    email character varying(150) NOT NULL,
    date_of_birth DATE NOT NULL,
    status character varying(15) NOT NULL
);

ALTER TABLE participant ADD CONSTRAINT participant_pkey PRIMARY KEY (id);

CREATE TABLE participant_aud (
	id varchar(36) NOT NULL,
	rev int4 NOT NULL,
	revtype int2,
    firstname character varying(50),
    lastname character varying(50),
    email character varying(150),
    date_of_birth DATE,
    status character varying(15),
	CONSTRAINT participant_aud_pkey PRIMARY KEY (id, rev)
);

ALTER TABLE participant_aud ADD CONSTRAINT fk_participant_aud_rev FOREIGN KEY (rev) REFERENCES revinfo(rev);

CREATE TABLE service (
    id character varying(36) NOT NULL,
    version int4 DEFAULT 0 NOT NULL,
    servicename character varying(150) NOT NULL
);

ALTER TABLE service ADD CONSTRAINT service_pkey PRIMARY KEY (id);

CREATE TABLE service_aud (
	id varchar(36) NOT NULL,
	rev int4 NOT NULL,
	revtype int2,
    servicename character varying(150),
	CONSTRAINT service_aud_pkey PRIMARY KEY (id, rev)
);

ALTER TABLE service_aud ADD CONSTRAINT fk_service_aud_rev FOREIGN KEY (rev) REFERENCES revinfo(rev);

CREATE TABLE plan (
    id character varying(36) NOT NULL,
    version int4 DEFAULT 0 NOT NULL,
    name varchar(50) NOT NULL,
    description varchar(255),
    date_from TIMESTAMP NOT NULL,
    date_until TIMESTAMP NOT NULL
);

ALTER TABLE plan ADD CONSTRAINT plan_pkey PRIMARY KEY (id);

CREATE TABLE plan_aud (
	id varchar(36) NOT NULL,
	rev int4 NOT NULL,
	revtype int2,
    name varchar(50),
    description varchar(255),
    date_from TIMESTAMP,
    date_until TIMESTAMP
);

ALTER TABLE plan_aud ADD CONSTRAINT fk_plan_aud_rev FOREIGN KEY (rev) REFERENCES revinfo(rev);

CREATE TABLE plan_entry (
    id character varying(36) NOT NULL,
    version int4 DEFAULT 0 NOT NULL,
    start_time TIMESTAMP NOT NULL,
    end_time TIMESTAMP NOT NULL,
    service_id character varying(36),
    participant_id character varying(36),
    plan_id character varying(36)
);

ALTER TABLE plan_entry ADD CONSTRAINT plan_entry_pkey PRIMARY KEY (id);
ALTER TABLE plan_entry ADD CONSTRAINT fk_plan_entry_service_id FOREIGN KEY (service_id) REFERENCES service(id);
ALTER TABLE plan_entry ADD CONSTRAINT fk_plan_entry_participant_id FOREIGN KEY (participant_id) REFERENCES participant(id);
ALTER TABLE plan_entry ADD CONSTRAINT fk_plan_entry_plan_id FOREIGN KEY (plan_id) REFERENCES plan(id);

CREATE TABLE plan_entry_aud (
	id character varying(36) NOT NULL,
	rev int4 NOT NULL,
	revtype int2,
    start_time TIMESTAMP,
    end_time TIMESTAMP,
    service_id character varying(36),
    participant_id character varying(36),
    plan_id character varying(36)
);

ALTER TABLE plan_entry_aud ADD CONSTRAINT fk_plan_entry_aud_rev FOREIGN KEY (rev) REFERENCES revinfo(rev);

CREATE TABLE participant_service (
    participant_id character varying(36) NOT NULL,
    service_id character varying(36) NOT NULL
);

ALTER TABLE participant_service ADD CONSTRAINT participant_service_pkey PRIMARY KEY (participant_id, service_id);
ALTER TABLE participant_service ADD CONSTRAINT fk_participant_service_service_id FOREIGN KEY (service_id) REFERENCES service(id);
ALTER TABLE participant_service ADD CONSTRAINT fk_participant_service_participant_id FOREIGN KEY (participant_id) REFERENCES participant(id);

CREATE TABLE participant_service_aud (
    rev int4 NOT NULL,
	revtype int2,
    participant_id BIGINT NOT NULL,
    service_id BIGINT NOT NULL
);

ALTER TABLE participant_service_aud ADD CONSTRAINT fk_participant_service_aud_rev FOREIGN KEY (rev) REFERENCES revinfo(rev);